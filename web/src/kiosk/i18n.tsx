export const LANG_NATIVE_NAMES: Record<KioskLang, string> = {
  tr: "Türkçe",
  en: "English",
  ru: "Русский",
  de: "Deutsch",
  ar: "العربية",
};

export function LanguageSwitcher({ children }: { children?: ReactNode } = {}) {
  const { lang, setLang } = useKioskLang();
  return (
    <div className="kiosk-lang-switcher">
      {LANG_OPTIONS.map((opt) => (
        <button key={opt.code} type="button" className={lang === opt.code ? "active" : ""} onClick={() => setLang(opt.code)}>
          {opt.label}
        </button>
      ))}
      {children}
    </div>
  );
}
